#!/usr/bin/env bash
# Copies the owner's photos into assets/photos/ with clean kebab-case names,
# shrinks them to a 2000px long edge, and rewrites assets/js/photos-available.js
# so the site shows every photo that is present (and a placeholder for the rest).
#
# Usage: tools/import-photos.sh [source-dir]   (default: ~/Downloads)
# Needs macOS `sips`. Safe to re-run.
set -euo pipefail

SRC="${1:-$HOME/Downloads}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/assets/photos"
mkdir -p "$DEST"

# original file name (without extension) -> site file name (without extension)
map_name() {
  case "$1" in
    side_east_building) echo exterior-east-side ;;
    front_northwest_biulding|front_northwest_building) echo exterior-front-northwest ;;
    Front_northeast_building|front_northeast_building) echo exterior-front-northeast ;;
    "keyless_building front"|keyless_building_front) echo keyless-building-entry ;;
    keyless_Unitfront|keyless_unitfront) echo keyless-unit-entry ;;
    "Washer&dryer_Laundry"|washer_dryer_laundry) echo laundry-room ;;
    Hallway_outside|hallway_outside) echo hallway ;;
    Elevator|elevator) echo elevator ;;
    Bedroom1-Southwindow_E3) echo e3-bedroom-south-window ;;
    Bedroom1_Wardrobeinside_E3) echo e3-bedroom-wardrobe-open ;;
    Bedroom1_drawers_E3) echo e3-bedroom-bed-drawers ;;
    Bedroom1_Eastwindow_E3) echo e3-bedroom-east-window ;;
    Bedroom1_E3) echo e3-bedroom ;;
    "Bedroom1_desk&chair_E3") echo e3-bedroom-desk ;;
    Bedroom1_wardrobefront_E3) echo e3-bedroom-wardrobe ;;
    Bath1_E3) echo e3-bathroom ;;
    Frontdoor_E3) echo e3-front-door ;;
    KItchen_E3|Kitchen_E3) echo e3-kitchen ;;
    Kitchen2_E3) echo e3-kitchen-2 ;;
    Dining_B1) echo b1-dining ;;
    Bedroom1_B1) echo b1-bedroom-1 ;;
    Bedroom2_B1) echo b1-bedroom-2 ;;
    Bath_B1) echo b1-bathroom ;;
    Kitchen_B1) echo b1-kitchen ;;
    *) echo "" ;;
  esac
}

shopt -s nullglob nocaseglob
for f in "$SRC"/*.jpeg "$SRC"/*.jpg; do
  base="$(basename "$f")"
  stem="${base%.*}"
  name="$(map_name "$stem")"
  [ -z "$name" ] && continue
  out="$DEST/$name.jpg"
  sips -s format jpeg -s formatOptions 80 -Z 2000 "$f" --out "$out" >/dev/null
  # Small phone exports are often already well compressed; keep whichever file is smaller.
  if [ "$(stat -f%z "$f")" -lt "$(stat -f%z "$out")" ] && [ "$(sips -g pixelWidth -g pixelHeight "$f" | awk '/pixel/{if($2>m)m=$2}END{print m}')" -le 2000 ]; then
    cp "$f" "$out"
  fi
  echo "imported $base -> assets/photos/$name.jpg"
done

# Regenerate the list of photos that exist on disk.
{
  echo "// Generated by tools/import-photos.sh. Lists the photo files present in assets/photos/."
  echo "window.LUTTRELL_PHOTOS_AVAILABLE = ["
  for p in "$DEST"/*.jpg; do echo "  \"$(basename "$p")\","; done
  echo "];"
} > "$ROOT/assets/js/photos-available.js"
echo "updated assets/js/photos-available.js"
